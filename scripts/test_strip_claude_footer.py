import importlib.machinery
import importlib.util
import io
import json
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

path = str(Path(__file__).with_name("strip-claude-footer"))
loader = importlib.machinery.SourceFileLoader("strip_claude_footer", path)
spec = importlib.util.spec_from_loader("strip_claude_footer", loader)
sf = importlib.util.module_from_spec(spec)
loader.exec_module(sf)

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


class StripFooter(unittest.TestCase):
    def test_strips_the_footer_the_proxy_appends(self):
        self.assertEqual(sf.strip_footer("comment test" + FOOTER), "comment test")
        self.assertEqual(sf.strip_footer("a\n\nb" + FOOTER + "\n"), "a\n\nb")

    def test_leaves_a_body_without_it(self):
        self.assertIsNone(sf.strip_footer("plain"))
        self.assertIsNone(sf.strip_footer(None))
        self.assertIsNone(sf.strip_footer("quoted: _Generated by [Claude Code](https://claude.ai/code)_ mid-text\nmore"))


class FakeGh:
    """Answers the list endpoints from fixtures and records each PATCH."""

    def __init__(self, issues=(), comments=(), review_comments=()):
        self.lists = {"issues?": issues, "issues/comments?": comments, "pulls/comments?": review_comments}
        self.patches = []

    def __call__(self, *args, body=None):
        if args[:2] == ("-X", "PATCH"):
            self.patches.append((args[2], body))
            return "{}"
        path = args[1]
        for key, items in self.lists.items():
            if path.split("/", 3)[3].startswith(key):
                return "\n".join(json.dumps(i) for i in items)
        raise AssertionError(path)


def run(argv, api, env=None):
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        code = sf.main(argv, api=api, env=env or {})
    return code, out.getvalue(), err.getvalue()


class Main(unittest.TestCase):
    def fake(self):
        return FakeGh(
            issues=[{"number": 5, "body": "issue" + FOOTER},
                    {"number": 6, "body": "pr body" + FOOTER, "pull_request": {}},
                    {"number": 7, "body": "clean"}],
            comments=[{"id": 70, "body": "comment" + FOOTER}, {"id": 71, "body": "human"}],
            review_comments=[{"id": 90, "body": "nit" + FOOTER}],
        )

    def test_strips_every_body_that_ends_in_the_footer(self):
        api = self.fake()
        code, out, _ = run(["o/r", "--since", "2026-11-20"], api)
        self.assertEqual(code, 0)
        self.assertEqual(api.patches, [
            ("repos/o/r/issues/5", "issue"), ("repos/o/r/issues/6", "pr body"),
            ("repos/o/r/issues/comments/70", "comment"), ("repos/o/r/pulls/comments/90", "nit"),
        ])
        self.assertIn("stripped pr #6", out)
        self.assertIn("stripped review comment 90", out)

    def test_dry_run_changes_nothing(self):
        api = self.fake()
        code, out, _ = run(["o/r", "--dry-run"], api)
        self.assertEqual((code, api.patches), (0, []))
        self.assertIn("would strip issue #5", out)

    def test_refuses_in_a_cloud_session(self):
        api = self.fake()
        code, _, err = run(["o/r"], api, env={"CLAUDE_CODE_REMOTE": "true"})
        self.assertEqual((code, api.patches), (2, []))
        self.assertIn("cloud session", err)

    def test_says_so_when_nothing_has_the_footer(self):
        code, out, _ = run(["o/r", "--since", "2026-11-20"], FakeGh())
        self.assertEqual(code, 0)
        self.assertIn("nothing to strip since 2026-11-20", out)

    def test_a_failed_call_exits_1(self):
        def broken(*args, body=None):
            raise RuntimeError("gh api: HTTP 404")
        code, _, err = run(["o/r"], broken)
        self.assertEqual(code, 1)
        self.assertIn("HTTP 404", err)


if __name__ == "__main__":
    unittest.main()
