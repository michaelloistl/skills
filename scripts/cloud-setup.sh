#!/usr/bin/env bash
# Setup script for Claude Code cloud environments (claude.ai/code).
# Runs as root on Ubuntu before Claude Code launches. The result is cached for
# ~7 days and rebuilt only when the pasted script changes, so paste this loader
# pinned to a commit, and bump SKILLS_REF to roll out a change:
#
#   #!/bin/bash
#   set -euo pipefail
#   export SKILLS_REF=<full commit sha>
#   f=$(mktemp)
#   curl -fsSL "https://raw.githubusercontent.com/michaelloistl/skills/$SKILLS_REF/scripts/cloud-setup.sh" -o "$f"
#   bash "$f" </dev/null
#
# SKILLS_REF pins this repo's skills and hooks too. Network: the default
# Limited level with "Allow package managers" checked reaches every host used
# here (github.com, raw.githubusercontent.com, registry.npmjs.org).

set -euo pipefail

# This repo at SKILLS_REF: its skills and hooks install from this checkout.
# A sha must be the full 40 characters: GitHub fetches no abbreviated one.
src=$(mktemp -d)
git -C "$src" init -q
git -C "$src" fetch -q --depth 1 https://github.com/michaelloistl/skills "${SKILLS_REF:-main}"
git -C "$src" checkout -q FETCH_HEAD

MATT_SKILLS=(
  code-review codebase-design diagnosing-bugs domain-modeling grill-with-docs
  grilling handoff implement implement-spec improve-codebase-architecture pr
  prototype research retro tdd to-spec to-tickets
  triage wayfinder writing-for-agents
)

npx -y skills@latest add mattpocock/skills -g -y --agent claude-code --copy \
  --skill "${MATT_SKILLS[@]}" </dev/null
npx -y skills@latest add "$src" -g -y --agent claude-code --copy \
  --skill '*' </dev/null

mkdir -p ~/.claude/hooks

# Every executable in hooks/ is a hook; its tests are not executable.
for hook in "$src"/hooks/*; do
  [ -f "$hook" ] && [ -x "$hook" ] && install -m 755 "$hook" ~/.claude/hooks/
done

# Mods that work in a cloud session, loaded through CLAUDE_CODE_PLUGIN_DIRS in
# settings.json below. Their Rex panes stay behind: no Rex here.
CLOUD_MODS=(drive-spec-view)
mkdir -p ~/.claude/mods
for mod in "${CLOUD_MODS[@]}"; do
  rm -rf ~/.claude/mods/"$mod"
  cp -R "$src/mods/$mod" ~/.claude/mods/
  rm -rf ~/.claude/mods/"$mod"/rex
done
plugin_dirs=$(printf "$HOME/.claude/mods/%s:" "${CLOUD_MODS[@]}")
plugin_dirs=${plugin_dirs%:}

cat > ~/.claude/CLAUDE.md <<'EOF'
Be extremely concise. Sacrifice grammar for the sake of concision.

Search code with `rg` or `git grep`: both skip ignored build output.

## Debugging

When stuck on a bug — after 3+ failed fix attempts, when about to make a low-confidence guess, or when the same assumption has been made multiple times — you MUST invoke the `debug-logs` skill instead of continuing to guess. Do not attempt another fix. Instrument the code first.

## Git

Only create commits when explicitly asked. Do not auto-commit during feature work.
Stage the paths you changed by name (`git add <path>…`): the user and other sessions share the checkout, and their edits sit uncommitted beside yours.
When committing, write only the commit message subject line — leave the detailed description body empty.
Do not add Co-Authored-By lines to commit messages.
Never add a Claude Code attribution footer (the "🤖 Generated with [Claude Code]" line, the "_Generated by [Claude Code](https://claude.ai/code)_" line, or any `claude.com/claude-code` or `claude.ai/code` link) to any commit message, PR body, GitHub issue body, or issue comment — including `gh pr create`, `gh pr edit`, `gh issue create`, `gh issue edit`, and every `gh api` call that sends a `body`.

## GitHub in cloud sessions

The GitHub proxy rejects GraphQL, so `gh issue …` and `gh pr …` fail with 403. Use the REST API via `gh api repos/{owner}/{repo}/…` instead, e.g.:
- view issue: `gh api repos/{owner}/{repo}/issues/<n>`
- create issue: `gh api repos/{owner}/{repo}/issues -f title=… -f body=…`
- comment: `gh api repos/{owner}/{repo}/issues/<n>/comments -f body=…`
- labels: `gh api repos/{owner}/{repo}/issues/<n>/labels -f 'labels[]=…'`
- close: `gh api -X PATCH repos/{owner}/{repo}/issues/<n> -f state=closed`
- create PR: `gh api repos/{owner}/{repo}/pulls -f base=… -f head=… -f title=… -f body=… -F draft=true`
- merge PR: `gh api -X PUT repos/{owner}/{repo}/pulls/<n>/merge -f merge_method=merge`
The proxy also rejects remote branch deletion: leave merged branches on origin.
The proxy appends a `_Generated by [Claude Code](https://claude.ai/code)_` footer to every issue, PR and comment it writes, edits included. You cannot remove it: never edit a body to strip it, and don't report it. The operator strips it later from their own machine.
EOF

# Hooks as hooks/README.md registers them; the mods' folders go in `env` after.
cat > ~/.claude/settings.json <<'EOF'
{
  "attribution": false,
  "hooks": {
    "PreToolUse": [
      {"matcher": "Bash", "hooks": [
        {"type": "command", "command": "~/.claude/hooks/block-claude-attribution.sh"},
        {"type": "command", "command": "~/.claude/hooks/block-unbounded-wait.sh"},
        {"type": "command", "command": "~/.claude/hooks/block-git-stash.sh"},
        {"type": "command", "command": "~/.claude/hooks/block-drive-spec-pipe.py"}
      ]}
    ],
    "SessionStart": [
      {"hooks": [{"type": "command", "command": "~/.claude/hooks/check-hooks-installed.py", "timeout": 5}]}
    ]
  }
}
EOF
settings=~/.claude/settings.json
jq --arg dirs "$plugin_dirs" '.env.CLAUDE_CODE_PLUGIN_DIRS = $dirs' "$settings" > "$settings.tmp" \
  && mv "$settings.tmp" "$settings"

rm -rf "$src"
